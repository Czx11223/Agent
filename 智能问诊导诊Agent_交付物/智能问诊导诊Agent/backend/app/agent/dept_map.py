def find_past_history(text: str) -> str:
    """抽取既往病史（"有癫痫病史"或直接给出病名），无则返回空串。"""
    t = (text or "").strip()
    for d in CHRONIC_DISEASES:
        if d in t:
            return d
    return ""


# 恐惧类表述（"害怕晕倒"“担心休克”）并非已发生的急症，匹配急症关键词前先剔除
_FEAR_RE = re.compile(
    r"(?:害怕|怕|担心|生怕|恐怕)(?:会|可能|要是)?(晕倒|昏迷|休克|窒息|抽搐|大出血|吐血|咯血)"
)


def is_emergency(text: str) -> bool:
    t = _FEAR_RE.sub("", text or "")
    return any(k in t for k in EMERGENCY_KEYWORDS)


def recommend_top3(complaint: str, extra: str = "") -> list[dict]:
    """按主诉直接命中科室关键词，多症状加权取 Top3。"""
    corpus = f"{complaint} {extra}"
    scores: dict[str, int] = {}
    for dept, kws in DEPT_KEYWORDS.items():
        cnt = sum(1 for k in kws if k in corpus)
        if cnt:
            scores[dept] = cnt
    if not scores:
        return [{"dept": "内科全科", "reason": "未能明确指征，建议先挂全科/内科评估"}]
    ranked = sorted(scores.items(), key=lambda x: (-x[1], x[0]))[:3]
    return [{"dept": d, "reason": f"主诉含与{d}相关的症状（匹配 {c} 项）"} for d, c in ranked]